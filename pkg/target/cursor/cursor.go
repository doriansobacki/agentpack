// Package cursor is the (experimental) Cursor target.
//
// Cursor currently exposes no file-based user-level rules surface: User Rules
// live in the app's settings and Team Rules in the Cursor dashboard, while
// repo-level AGENTS.md / .cursor/rules are per-repository concerns. Until
// Cursor ships a file or API surface agentpack can write directly, this
// target renders the merged rules to a paste-ready file and points the user
// at it. Rules-only: memories, skills, and agents have no Cursor equivalent.
package cursor

import "github.com/doriansobacki/agentpack/pkg/target"

// Name is this target's identifier in the org manifest's targets: list.
const Name = "cursor"

const header = `<!-- Generated by agentpack (experimental Cursor target).
Cursor has no user-level rules file agentpack can write directly. Paste the
content below into Cursor Settings > Rules (User Rules), or publish it as
enforced Team Rules from the Cursor dashboard. -->

`

// Target implements target.Target for Cursor.
type Target struct{}

// New returns the Cursor target.
func New() *Target { return &Target{} }

// Name implements target.Target.
func (*Target) Name() string { return Name }

// Apply implements target.Target.
func (*Target) Apply(ctx *target.Context) (*target.Result, error) {
	res, err := target.WriteGenerated(ctx, "cursor-user-rules.md", header, target.MergedMarkdown(ctx.Packs, false))
	if err != nil {
		return nil, err
	}
	for _, dest := range res.Files {
		res.Warnings = append(res.Warnings,
			"cursor target is experimental: wrote "+dest+" for manual import (Cursor exposes no user-level rules file yet)")
	}
	return res, nil
}
