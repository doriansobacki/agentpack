// Package agentsmd materializes all packs' rules and memories into one
// merged AGENTS.md under agentpack's generated directory. Repositories (or
// tools that read the cross-vendor AGENTS.md standard from a global location)
// can reference it, e.g. from a repo-level AGENTS.md import line.
package agentsmd

import (
	"os"
	"path/filepath"

	"github.com/doriansobacki/agentpack/pkg/target"
)

const header = "<!-- Generated by agentpack. Do not edit: this file is rewritten on every sync. -->\n\n"

// Target implements target.Target for the AGENTS.md standard.
type Target struct{}

// New returns the AGENTS.md target.
func New() *Target { return &Target{} }

// Name implements target.Target.
func (*Target) Name() string { return "agentsmd" }

// Apply implements target.Target.
func (*Target) Apply(ctx *target.Context) (*target.Result, error) {
	content := target.MergedMarkdown(ctx.Packs, true)
	if content == "" {
		return &target.Result{}, nil
	}
	dest := filepath.Join(ctx.GeneratedDir, "AGENTS.md")
	if !ctx.DryRun {
		if err := os.MkdirAll(ctx.GeneratedDir, 0o755); err != nil {
			return nil, err
		}
		if err := os.WriteFile(dest, []byte(header+content+"\n"), 0o644); err != nil {
			return nil, err
		}
	}
	return &target.Result{Files: []string{dest}}, nil
}
